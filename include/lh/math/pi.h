/**
 * @file pi.h
 * @brief The circle constant, in ::lh_float_t.
 */

#ifndef LH_MATH_PI_H
#define LH_MATH_PI_H

#include <lh/float.h>

/**
 * @def LH_MATH_PI
 * @brief π. One full turn is twice this. Single precision, same as
 *        ::lh_float_t, so a radian stays off the software `double` path.
 */
#define LH_MATH_PI 3.14159265f

#endif /* LH_MATH_PI_H */
