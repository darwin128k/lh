TEST(crypto_ed25519_scalar, reduce_of_l_is_zero)
{
    wide w{};
    for (std::size_t i = 0; i < l_bytes.size(); ++i)
    {
        w[i] = l_bytes[i];
    }
    scalar r;
    r.fill(0xaau);
    lh_crypto_ed25519_scalar_reduce(r.data(), w.data());
    EXPECT_EQ(r, scalar{});
}

