using scalar = std::array<lh_byte_t, LH_CRYPTO_ED25519_SCALAR_SIZE>;
using wide = std::array<lh_byte_t, 2U * LH_CRYPTO_ED25519_SCALAR_SIZE>;
using words = std::array<lh_u32_t, LH_CRYPTO_ED25519_SCALAR_WORDS>;

/* The expected values below were computed with Python's integers. */

const scalar l_bytes = {0xed, 0xd3, 0xf5, 0x5c, 0x1a, 0x63, 0x12, 0x58, 0xd6, 0x9c, 0xf7,
                        0xa2, 0xde, 0xf9, 0xde, 0x14, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
                        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10};

words
l_plus(lh_u32_t n)
{
    words w{};
    const lh_u32_t *l = lh_crypto_ed25519_scalar_get_l();
    lh_u64_t carry = n;
    for (std::size_t i = 0; i < w.size(); ++i)
    {
        carry += l[i];
        w[i] = static_cast<lh_u32_t>(carry);
        carry >>= 32;
    }
    return w;
}

TEST(crypto_ed25519_scalar, l_is_the_group_order)
{
    const lh_u32_t *l = lh_crypto_ed25519_scalar_get_l();
    for (std::size_t i = 0; i < LH_CRYPTO_ED25519_SCALAR_WORDS; ++i)
    {
        const lh_u32_t expected = static_cast<lh_u32_t>(l_bytes[4 * i]) |
                                  static_cast<lh_u32_t>(l_bytes[4 * i + 1]) << 8 |
                                  static_cast<lh_u32_t>(l_bytes[4 * i + 2]) << 16 |
                                  static_cast<lh_u32_t>(l_bytes[4 * i + 3]) << 24;
        EXPECT_EQ(l[i], expected) << i;
    }
}

TEST(crypto_ed25519_scalar, trim_clears_and_sets_the_rfc_8032_bits)
{
    scalar s;
    s.fill(0xffu);
    lh_crypto_ed25519_scalar_trim(s.data(), s.data());
    EXPECT_EQ(s[0], 0xf8u);
    EXPECT_EQ(s[31], 0x7fu);
    s.fill(0x00u);
    lh_crypto_ed25519_scalar_trim(s.data(), s.data());
    EXPECT_EQ(s[0], 0x00u);
    EXPECT_EQ(s[31], 0x40u);
}

TEST(crypto_ed25519_scalar, get_bit_reads_little_endian_bits_and_minus_one_is_zero)
{
    scalar s{};
    s[0] = 0x01u;
    s[1] = 0x80u;
    s[31] = 0x80u;
    EXPECT_EQ(lh_crypto_ed25519_scalar_get_bit(s.data(), -1), 0);
    EXPECT_EQ(lh_crypto_ed25519_scalar_get_bit(s.data(), 0), 1);
    EXPECT_EQ(lh_crypto_ed25519_scalar_get_bit(s.data(), 1), 0);
    EXPECT_EQ(lh_crypto_ed25519_scalar_get_bit(s.data(), 15), 1);
    EXPECT_EQ(lh_crypto_ed25519_scalar_get_bit(s.data(), 255), 1);
}

TEST(crypto_ed25519_scalar, is_above_l_is_at_or_above)
{
    words below = l_plus(0);
    below[0] -= 1u; /* L - 1: L's lowest word is not 0 */
    EXPECT_FALSE(lh_crypto_ed25519_scalar_is_above_l(below.data()));
    EXPECT_TRUE(lh_crypto_ed25519_scalar_is_above_l(l_plus(0).data()));
    EXPECT_TRUE(lh_crypto_ed25519_scalar_is_above_l(l_plus(1).data()));
    const words zero{};
    EXPECT_FALSE(lh_crypto_ed25519_scalar_is_above_l(zero.data()));
}

TEST(crypto_ed25519_scalar, remove_l_subtracts_only_at_or_above_l)
{
    words r{};
    lh_crypto_ed25519_scalar_remove_l(r.data(), l_plus(5).data());
    EXPECT_EQ(r, (words{5u, 0, 0, 0, 0, 0, 0, 0}));
    const words small = {9u, 0, 0, 0, 0, 0, 0, 0};
    lh_crypto_ed25519_scalar_remove_l(r.data(), small.data());
    EXPECT_EQ(r, small);
}

TEST(crypto_ed25519_scalar, multiply_adds_the_product_to_the_lower_half)
{
    std::array<lh_u32_t, 16> p{};
    p[0] = 7u;
    p[12] = 0xdeadbeefu; /* the upper half is ignored */
    const words a = {0xffffffffu, 0, 0, 0, 0, 0, 0, 0};
    const words b = {0xffffffffu, 0, 0, 0, 0, 0, 0, 0};
    lh_crypto_ed25519_scalar_multiply(p.data(), a.data(), b.data());
    /* (2^32 - 1)^2 + 7 = 0xfffffffe_00000008 */
    EXPECT_EQ(p[0], 0x00000008u);
    EXPECT_EQ(p[1], 0xfffffffeu);
    for (std::size_t i = 2; i < p.size(); ++i)
    {
        EXPECT_EQ(p[i], 0u) << i;
    }
}

