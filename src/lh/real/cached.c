lh_real_diy_t
lh_real_cached_get(lh_usize_t index)
{
    lh_assert_runtime_if(lh_math_ge(index, LH_REAL_CACHED_COUNT),
                         lh_runtime_error_code_out_of_range);
    return lh_real_diy_make(m_real_cached[index].f, m_real_cached[index].e);
}

lh_s32_t
lh_real_cached_get_k(lh_usize_t index)
{
    return lh_math_add(LH_REAL_CACHED_K_MIN,
                       lh_math_mul(LH_REAL_CACHED_K_STEP, lh_cast_static(lh_s32_t, index)));
}

lh_usize_t
lh_real_cached_find(lh_s32_t e)
{
    /* 10^k must bring an exponent e into [-60, -32] after the 64-bit product:
       k ≈ (-61 - e) × log10(2). 78913 / 2^18 is log10(2) to six digits; the
       loops below make up for what it is off. */
    const lh_s32_t x = lh_math_sub(-61, e);
    const lh_s32_t k = lh_cast_static(
        lh_s32_t, lh_math_div(lh_math_mul(lh_cast_static(lh_s64_t, x), 78913), 262144));
    lh_s32_t index = lh_math_add_one(
        lh_math_div(lh_math_sub(lh_math_add(k, 1), LH_REAL_CACHED_K_MIN), LH_REAL_CACHED_K_STEP));

    index = lh_math_clamp(index, 0, LH_REAL_CACHED_COUNT - 1);
    while (lh_math_gt(index, 0) &&
           lh_math_gt(lh_math_add(lh_math_add(e, m_real_cached[index].e), 64), -32))
    {
        index = lh_math_sub_one(index);
    }
    while (lh_math_lt(index, LH_REAL_CACHED_COUNT - 1) &&
           lh_math_lt(lh_math_add(lh_math_add(e, m_real_cached[index].e), 64), -60))
    {
        index = lh_math_add_one(index);
    }
    return lh_cast_static(lh_usize_t, index);
}

